func genCommand(args []string) error {
	flags := flag.NewFlagSet("gen", flag.ExitOnError)
	dir := flags.String("dir", "schemas", "schema directory")
	pkg := flags.String("pkg", "msgs", "name of the generated Go package")
	out := flags.String("out", "messages_gen.go", "output file")
	flags.Parse(args)

	names, err := existingTypes(*dir)
	if err != nil {
		return err
	}
	if len(names) == 0 {
		return fmt.Errorf("no schemas in %s", *dir)
	}

	g := &generator{types: map[string]*genType{}}
	for _, name := range names {
		text, err := os.ReadFile(filepath.Join(*dir, filepath.FromSlash(name)+".msg"))
		if err != nil {
			return err
		}
		schema, err := ros2msg.Parse(name, string(text))
		if err != nil {
			return err
		}
		if err := g.add(schema); err != nil {
			return err
		}
	}

	src, err := g.generate(*pkg)
	if err != nil {
		return err
	}
	return os.WriteFile(*out, src, 0o644)
}

// genType is a message type to generate, with the schema it came from.
type genType struct {
	def    *ros2msg.Definition
	schema *ros2msg.Schema
}

func (t *genType) fingerprint() string {
	return t.schema.Fingerprint(t.def.Name)
}

type generator struct {
	types map[string]*genType // by fully qualified name
	buf   bytes.Buffer
}

// add registers every type of a schema. Types shared between schemas must
// have the same layout everywhere.
func (g *generator) add(schema *ros2msg.Schema) error {
	for name, def := range schema.Definitions {
		t := &genType{def: def, schema: schema}
		if prev, ok := g.types[name]; ok {
			if prev.fingerprint() != t.fingerprint() {
				return fmt.Errorf("%s has different definitions in %s and %s; fetch them again", name, prev.schema.Root.Name, schema.Root.Name)
			}
			continue
		}
		g.types[name] = t
	}
	return nil
}

func (g *generator) printf(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
}

func (g *generator) generate(pkg string) ([]byte, error) {
	g.printf("// Code generated by msggen. DO NOT EDIT.\n\n")
	g.printf("package %s\n\n", pkg)
	g.printf("import %q\n\n", "github.com/acristoffers/foxglove-client-go/cdr")
	g.printf(`// Message is implemented by every generated message type.
type Message interface {
	// SchemaName is the ROS type, e.g. "geometry_msgs/msg/Point".
	SchemaName() string
	// Fingerprint identifies the layout the type was generated from, see
	// ros2msg.Schema.Fingerprint.
	Fingerprint() string
	// UnmarshalCDR decodes a CDR payload, encapsulation header included.
	UnmarshalCDR(data []byte) error
}

func unmarshalCDR(data []byte, decode func(*cdr.Reader)) error {
	r, err := cdr.NewReader(data)
	if err != nil {
		return err
	}
	decode(r)
	return r.Err()
}

`)

	for _, name := range slices.Sorted(maps.Keys(g.types)) {
		if err := g.genType(g.types[name]); err != nil {
			return nil, err
		}
	}

	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated code: %w", err)
	}
	return src, nil
}

func (g *generator) genType(t *genType) error {
	def := t.def
	typeName := goTypeName(def.Name)

	fieldNames := map[string]string{}
	for _, f := range def.Fields {
		name := goFieldName(f.Name)
		if other, ok := fieldNames[name]; ok {
			return fmt.Errorf("%s: fields %s and %s both map to %s", def.Name, other, f.Name, name)
		}
		fieldNames[name] = f.Name
	}

	g.printf("// %s is the %s message.\n", typeName, schemaName(def.Name))
	g.printf("type %s struct {\n", typeName)
	for _, f := range def.Fields {
		typ, err := goType(f.Type)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", def.Name, f.Name, err)
		}
		g.printf("\t%s %s\n", goFieldName(f.Name), typ)
	}
	g.printf("}\n\n")

	if len(def.Constants) > 0 {
		g.printf("// Constants of %s.\nconst (\n", schemaName(def.Name))
		for _, c := range def.Constants {
			value, err := goConstant(c)
			if err != nil {
				return fmt.Errorf("%s.%s: %w", def.Name, c.Name, err)
			}
			typ, _ := goType(c.Type)
			g.printf("\t%s_%s %s = %s\n", typeName, c.Name, typ, value)
		}
		g.printf(")\n\n")
	}

	g.printf("// SchemaName implements Message.\n")
	g.printf("func (*%s) SchemaName() string { return %q }\n\n", typeName, schemaName(def.Name))
	g.printf("// Fingerprint implements Message.\n")
	g.printf("func (*%s) Fingerprint() string { return %q }\n\n", typeName, t.fingerprint())
	g.printf("// UnmarshalCDR implements Message.\n")
	g.printf("func (m *%s) UnmarshalCDR(data []byte) error { return unmarshalCDR(data, m.decode) }\n\n", typeName)

	g.printf("func (m *%s) decode(r *cdr.Reader) {\n", typeName)
	if len(def.Fields) == 0 {
		// Empty messages are serialized with a one byte placeholder.
		g.printf("\tr.Uint8()\n")
	}
	for _, f := range def.Fields {
		g.decodeField("m."+goFieldName(f.Name), f.Type)
	}
	g.printf("}\n\n")
	return nil
}

func (g *generator) decodeField(target string, t ros2msg.Type) {
	elem := t
	elem.Array, elem.Length = ros2msg.NotArray, 0
	byteLike := isByteLike(t.Name)

	switch {
	case t.Array == ros2msg.NotArray:
		g.decodeValue(target, t)
	case t.Array == ros2msg.FixedArray && byteLike:
		g.printf("\tcopy(%s[:], r.Bytes(%d))\n", target, t.Length)
	case t.Array == ros2msg.FixedArray:
		g.printf("\tfor i := range %s {\n", target)
		g.decodeValue(target+"[i]", elem)
		g.printf("\t}\n")
	case byteLike:
		g.printf("\t%s = r.Bytes(r.SequenceLength(1))\n", target)
	default:
		typ, _ := goType(elem)
		g.printf("\t%s = make([]%s, r.SequenceLength(%d))\n", target, typ, g.minSize(elem))
		g.printf("\tfor i := range %s {\n", target)
		g.decodeValue(target+"[i]", elem)
		g.printf("\t}\n")
	}
}

func (g *generator) decodeValue(target string, t ros2msg.Type) {
	if !t.IsPrimitive() {
		g.printf("\t%s.decode(r)\n", target)
		return
	}
	g.printf("\t%s = r.%s()\n", target, readerMethod[t.Name])
}

// minSize is the fewest bytes a value of the type can occupy, used to reject
// impossible sequence lengths early.
func (g *generator) minSize(t ros2msg.Type) int {
	switch t.Array {
	case ros2msg.UnboundedArray, ros2msg.BoundedArray:
		return 4
	case ros2msg.FixedArray:
		elem := t
		elem.Array = ros2msg.NotArray
		return t.Length * g.minSize(elem)
	}
	if t.IsPrimitive() {
		return ros2msg.PrimitiveSize(t.Name)
	}
	size := 0
	for _, f := range g.types[t.Name].def.Fields {
		size += g.minSize(f.Type)
	}
	return max(size, 1)
}

var readerMethod = map[string]string{
	"bool":    "Bool",
	"byte":    "Uint8",
	"char":    "Uint8",
	"int8":    "Int8",
	"uint8":   "Uint8",
	"int16":   "Int16",
	"uint16":  "Uint16",
	"int32":   "Int32",
	"uint32":  "Uint32",
	"int64":   "Int64",
	"uint64":  "Uint64",
	"float32": "Float32",
	"float64": "Float64",
	"string":  "String",
}

var goPrimitive = map[string]string{
	"bool":    "bool",
	"byte":    "byte",
	"char":    "uint8",
	"int8":    "int8",
	"uint8":   "uint8",
	"int16":   "int16",
	"uint16":  "uint16",
	"int32":   "int32",
	"uint32":  "uint32",
	"int64":   "int64",
	"uint64":  "uint64",
	"float32": "float32",
	"float64": "float64",
	"string":  "string",
}

func isByteLike(name string) bool {
	return name == "uint8" || name == "byte" || name == "char"
}

func goType(t ros2msg.Type) (string, error) {
	elem := goTypeName(t.Name)
	if t.IsPrimitive() {
		var ok bool
		if elem, ok = goPrimitive[t.Name]; !ok {
			return "", fmt.Errorf("type %s is not supported", t.Name)
		}
	}
	switch t.Array {
	case ros2msg.FixedArray:
		return fmt.Sprintf("[%d]%s", t.Length, elem), nil
	case ros2msg.UnboundedArray, ros2msg.BoundedArray:
		return "[]" + elem, nil
	default:
		return elem, nil
	}
}

func goConstant(c ros2msg.Constant) (string, error) {
	switch c.Type.Name {
	case "bool":
		switch strings.ToLower(c.Value) {
		case "true", "1":
			return "true", nil
		case "false", "0":
			return "false", nil
		}
		return "", fmt.Errorf("invalid bool constant %q", c.Value)
	case "string":
		v := c.Value
		if len(v) >= 2 && (v[0] == '"' || v[0] == '\'') && v[len(v)-1] == v[0] {
			v = v[1 : len(v)-1]
		}
		return strconv.Quote(v), nil
	case "wstring":
		return "", fmt.Errorf("wstring constants are not supported")
	default:
		if _, err := strconv.ParseFloat(c.Value, 64); err != nil {
			if _, err := strconv.ParseInt(c.Value, 0, 64); err != nil {
				return "", fmt.Errorf("invalid numeric constant %q", c.Value)
			}
		}
		return c.Value, nil
	}
}

// goTypeName names a message type after its package and type, dropping the
// conventional suffixes: geometry_msgs/Point becomes GeometryPoint and
// example_interfaces/Int32 becomes ExampleInt32.
func goTypeName(name string) string {
	pkg, typ, _ := strings.Cut(name, "/")
	pkg = strings.TrimSuffix(pkg, "_msgs")
	pkg = strings.TrimSuffix(pkg, "_interfaces")
	return camel(pkg) + typ
}

// reservedFields would clash with the methods of generated types.
var reservedFields = map[string]bool{"SchemaName": true, "Fingerprint": true, "UnmarshalCDR": true}

func goFieldName(name string) string {
	name = camel(name)
	if reservedFields[name] {
		name += "_"
	}
	return name
}

var initialisms = map[string]string{
	"id": "ID", "ids": "IDs", "url": "URL", "uri": "URI", "ip": "IP", "cpu": "CPU",
	"ram": "RAM", "ssd": "SSD", "gps": "GPS", "gnss": "GNSS", "imu": "IMU", "rtk": "RTK",
	"http": "HTTP", "uuid": "UUID", "utc": "UTC", "tcp": "TCP", "udp": "UDP",
}

// camel turns snake_case into CamelCase.
func camel(snake string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(snake, "_") {
		if part == "" {
			continue
		}
		if upper, ok := initialisms[strings.ToLower(part)]; ok {
			b.WriteString(upper)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}
